// Smoke checks for the public job-search API documentation generator.

import { loadDocsModules, renderMarkdown } from './gen-api-docs.mjs';
import { buildDeprecatedFixture } from './deprecatedFixture.mjs';

const checks = [];
function assert(name, condition) {
  checks.push({ name, ok: Boolean(condition) });
}

async function main() {
  const { spec, filters } = await loadDocsModules();
  const a = renderMarkdown(spec, filters);
  const b = renderMarkdown(spec, filters);

  assert('idempotent output', a === b);
  assert('generated header', a.includes('GENERATED by web/scripts/gen-api-docs.mjs'));
  assert('no leading blank line', !a.startsWith('\n'));
  assert('single trailing newline', a.endsWith('\n') && !a.endsWith('\n\n'));
  assert('base URL', a.includes('https://freehire.me/api/v1'));
  assert('filter section', a.includes('## Filtering jobs'));
  assert('keyword search', a.includes('GET /jobs/search'));
  assert('facet search', a.includes('GET /jobs/facets'));
  assert('job details', a.includes('GET /jobs/{slug}'));
  assert('company listings', a.includes('GET /companies'));
  assert('query suggestions', a.includes('GET /suggest'));
  assert('recent jobs stream', a.includes('GET /feed/recent'));
  assert('sitemap routes', a.includes('GET /jobs/sitemap'));
  assert('string facet vocabulary', a.includes('`seniority`'));
  assert('visa sponsorship filter', a.includes('`visa_sponsorship`'));
  assert('and-mode modifier', a.includes('_mode=and'));
  assert('exclude modifier', a.includes('_exclude'));
  assert('first filter recipe', a.includes(filters.RECIPES[0].query));

  const endpointKeys = spec.GROUPS.flatMap((group) =>
    group.endpoints.map((endpoint) => `${endpoint.method} ${endpoint.path}`),
  );
  const expectedEndpointKeys = [
    'GET /jobs',
    'GET /jobs/search',
    'GET /jobs/facets',
    'GET /jobs/{slug}',
    'GET /jobs/{slug}/similar',
    'GET /jobs/{slug}/copies',
    'GET /companies',
    'GET /companies/subindustries',
    'GET /companies/{slug}',
    'GET /companies/{slug}/hiring',
    'GET /companies/{slug}/closed-jobs',
    'GET /geo/cities',
    'GET /suggest',
    'GET /feed/recent',
    'GET /stats/catalog',
    'GET /jobs/sitemap',
    'GET /jobs/sitemap/fresh',
    'GET /jobs/sitemap/boundaries',
    'GET /companies/sitemap',
    'GET /companies/sitemap/boundaries',
  ];
  assert('all documented endpoints are unique', new Set(endpointKeys).size === endpointKeys.length);
  assert('all documented endpoints are public', spec.GROUPS.every((group) => group.endpoints.every((ep) => ep.auth === 'none')));
  assert(
    'documented endpoint inventory matches the public server',
    JSON.stringify([...endpointKeys].sort()) === JSON.stringify([...expectedEndpointKeys].sort()),
  );
  assert('link-intake endpoint omitted', !endpointKeys.includes('GET /jobs/find'));
  assert('account and recruiting routes omitted', !/\/(?:auth|me|assistant|talent|referral)\b/.test(a));
  assert('account-only filters omitted', !filters.FILTER_EXTRAS.some((filter) => filter.param === 'former_employers'));
  assert('application-form filter omitted', !filters.FILTER_EXTRAS.some((filter) => filter.param === 'apply_questions_max'));

  const deprecated = renderMarkdown(buildDeprecatedFixture(spec), filters);
  assert('deprecated endpoint marked', deprecated.includes('**Deprecated'));
  assert('replacement included', deprecated.includes('GET /fixture/v2/{id}'));
  assert('deprecation date included', deprecated.includes('2026-09-08'));

  let failed = 0;
  for (const check of checks) {
    if (!check.ok) failed++;
    console.log(`${check.ok ? 'PASS' : 'FAIL'}  ${check.name}`);
  }
  if (failed) {
    console.error(`\n${failed} check(s) failed`);
    process.exit(1);
  }
  console.log(`\nAll ${checks.length} checks passed.`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
